"""4->2->1 physical multiscale bootstrap for recurrent local non-rigid flow.

This is stage 2 after train_v4_local_bootstrap.py has proven that the recurrent
local updater can recover a synthetic local field at physical scale 1.

Protocol:
- local-only samples, 100%;
- learned global rigid alignment is bypassed (identity);
- recurrent local flow runs progressively at physical scales 4 -> 2 -> 1;
- scale-specific targets are generated by Innovation-1 itself:
    target_4 = D~_{t4}(target)
    target_2 = D~_{t2}(target)
    target_1 = target
  where t4/t2 are the representative timesteps used by the V4 aligner.
  Flow values remain in HR-pixel units; only spatial frequency/detail is
  reduced by the physical degradation/lift operator.
- no reconstruction/SAM/zero-response/smoothness losses are used.

The goal is to verify that the successful scale-1 recurrent estimator remains
stable when its residual flow is decomposed along the physical degradation
trajectory.
"""

